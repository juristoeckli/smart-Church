export type AuthTranslationKey = keyof typeof authTranslations.en;

export function useAuthLanguage(initialLanguage?: UserLanguage) {
  const [language, setLanguage] = useState<UserLanguage>(() => {
    if (initialLanguage) return initialLanguage;
    try {
      const queryLanguage = new URLSearchParams(window.location.search).get("lang");
      if (queryLanguage === "en" || queryLanguage === "de" || queryLanguage === "fr" || queryLanguage === "it") return queryLanguage;
    } catch { /* Fall back to the saved or browser language. */ }
    try {
      const saved = window.localStorage.getItem("smart-church.auth-language");
      if (saved === "en" || saved === "de" || saved === "fr" || saved === "it") return saved;
    } catch { /* Use the browser language if storage is unavailable. */ }
    return browserDefaultLanguage();
  });

  useEffect(() => { setActiveLanguage(language); }, [language]);

  function selectLanguage(value: UserLanguage) {
    setLanguage(value);
    try { window.localStorage.setItem("smart-church.auth-language", value); } catch { /* The selection still applies for this page. */ }
  }

  return { language, selectLanguage, t: (key: AuthTranslationKey) => authTranslations[language][key] };
}

export function AuthLanguageSelect({ language, onChange, label }: { language: UserLanguage; onChange: (language: UserLanguage) => void; label: string }) {
  return <label className="auth-language-control"><span>{label}</span><select aria-label={label} value={language} onChange={(event) => onChange(event.target.value as UserLanguage)}>{(["en", "de", "fr", "it"] as UserLanguage[]).map((option) => <option key={option} value={option}>{languageNames[option]}</option>)}</select></label>;
}
